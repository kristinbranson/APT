classdef NavPrefsController < handle
  % Controller for the "Navigation Preferences" dialog (Ctrl-arrow frame
  % increment, playback speed and loop radius, and the Shift-arrow seek mode
  % with its timeline-statistic threshold).
  %
  % This replaces the legacy GUIDE app NavPrefsNew.m / NavPrefsNewMat.m.  The
  % figure is built programmatically in createGui_() (layout lifted from
  % GUIDE's export), the widget handles live as instance properties (no more
  % guidata reach-throughs), and the dialog is modal but non-blocking (no
  % uiwait): the constructor returns immediately, and Apply writes the edited
  % values to the Labeler and closes the dialog, while Cancel just closes it.

  properties (Transient)
    hFig  % the dialog figure
    parent_  % a LabelerController
    labeler_  % a Labeler

    % State (formerly stored in pumShiftArrow's UserData)
    shiftArrowModes_  % [n x 1] ShiftArrowMovieNavMode, one per entry of pumShiftArrow_

    % Widget handles, formerly reached via guidata(obj.hFig).
    etFrameSkip_
    etPlaybackSpeed_
    etPlaybackLoopDiameter_
    pumShiftArrow_
    txTimelineProp_  % name of the current timeline statistic, thresholded by the NEXTTIMELINETHRESH mode
    pumShiftArrowTimelineThreshCmp_
    etShiftArrowTimelineThresh_
    pbApply_
    pbCancel_
  end  % properties

  methods
    function obj = NavPrefsController(parent, labeler)
      % Build the dialog and initialize its controls from the Labeler.
      obj.parent_ = parent ;
      obj.labeler_ = labeler ;

      obj.createGui_() ;
      obj.initControlsFromModel_() ;
      obj.updateTimelineStatComparisonEnable_() ;

      obj.hFig.Visible = 'on' ;
    end  % function

    function delete(obj)
      % Tear down the figure.
      deleteValidGraphicsHandles(obj.hFig) ;
      obj.hFig = [] ;
    end  % function

    function createGui_(obj)
