        'Position', [2916 915 551 248], ...
        'Visible', 'off', ...
        'MenuBar', 'none', ...
        'ToolBar', 'none', ...
        'DockControls', 'off', ...
        'NumberTitle', 'off', ...
        'IntegerHandle', 'off', ...
        'Name', 'Navigation Preferences', ...
        'WindowStyle', 'modal', ...
        'Resize', 'off', ...
        'Tag', 'figure_navprefs', ...
        'CloseRequestFcn', @(s,e)(obj.closeRequested_())) ;

      % Playback speed
      uicontrol(...
        'Parent', obj.hFig, ...
        'Style', 'text', ...
        'Units', 'pixels', ...
        'FontUnits', 'pixels', ...
        'HorizontalAlignment', 'right', ...
        'String', 'Playback speed (fps):', ...
        'Position', [14 198 200 30], ...
        'FontSize', 16, ...
        'FontWeight', 'bold', ...
        'Tag', 'text4') ;

      obj.etPlaybackSpeed_ = uicontrol(...
        'Parent', obj.hFig, ...
        'Style', 'edit', ...
        'Units', 'pixels', ...
        'FontUnits', 'pixels', ...
        'HorizontalAlignment', 'left', ...
        'String', '', ...
        'Position', [219 204 90 30], ...
        'BackgroundColor', [1 1 1], ...
        'FontSize', 13.3333333333333, ...
        'Tooltip', 'Frames per second during playback', ...
        'Tag', 'etPlaybackSpeed', ...
        'Callback', @(s,e)(obj.etPlaybackSpeedActuated_())) ;

      % Playback loop radius
      uicontrol(...
        'Parent', obj.hFig, ...
        'Style', 'text', ...
        'Units', 'pixels', ...
        'FontUnits', 'pixels', ...
        'HorizontalAlignment', 'right', ...
        'String', 'Playback loop radius:', ...
        'Position', [14 165 200 30], ...
        'FontSize', 16, ...
        'FontWeight', 'bold', ...
        'Tag', 'text6') ;

      obj.etPlaybackLoopDiameter_ = uicontrol(...
        'Parent', obj.hFig, ...
        'Style', 'edit', ...
        'Units', 'pixels', ...
        'FontUnits', 'pixels', ...
        'HorizontalAlignment', 'left', ...
        'String', '', ...
        'Position', [219 171 90 30], ...
        'BackgroundColor', [1 1 1], ...
        'FontSize', 13.3333333333333, ...
        'Tooltip', 'Number of frames shown during segment/loop playback', ...
        'Tag', 'etPlaybackLoopDiameter', ...
        'Callback', @(s,e)(obj.etPlaybackLoopDiameterActuated_())) ;

      % Ctrl-arrow frame increment
      uicontrol(...
        'Parent', obj.hFig, ...
        'Style', 'text', ...
        'Units', 'pixels', ...
        'FontUnits', 'pixels', ...
        'HorizontalAlignment', 'right', ...
        'String', {'Ctrl-left/right ' ; 'frame increment:'}, ...
        'Position', [14 111 200 45], ...
        'FontSize', 16, ...
        'FontWeight', 'bold', ...
        'Tag', 'text2') ;

      obj.etFrameSkip_ = uicontrol(...
        'Parent', obj.hFig, ...
        'Style', 'edit', ...
        'Units', 'pixels', ...
        'FontUnits', 'pixels', ...
        'HorizontalAlignment', 'left', ...
        'String', '', ...
        'Position', [219 127 90 30], ...
        'BackgroundColor', [1 1 1], ...
        'FontSize', 13.3333333333333, ...
        'Tooltip', 'Number of frames to skip when using up/down arrows', ...
        'Tag', 'etFrameSkip', ...
        'Callback', @(s,e)(obj.etFrameSkipActuated_())) ;

      % Shift-arrow seek mode
      uicontrol(...
        'Parent', obj.hFig, ...
        'Style', 'text', ...
        'Units', 'pixels', ...
        'FontUnits', 'pixels', ...
        'HorizontalAlignment', 'right', ...
        'String', 'Shift-left/right seeks:', ...
        'Position', [14 81 200 30], ...
        'FontSize', 16, ...
        'FontWeight', 'bold', ...
        'Tag', 'text3') ;

      obj.pumShiftArrow_ = uicontrol(...
        'Parent', obj.hFig, ...
        'Style', 'popupmenu', ...
        'Units', 'pixels', ...
        'FontUnits', 'pixels', ...
        'String', {'Pop-up Menu'}, ...
        'Position', [219 89 317 30], ...
        'BackgroundColor', [1 1 1], ...
        'FontSize', 13.3333333333333, ...
        'Tag', 'pumShiftArrow', ...
        'Callback', @(s,e)(obj.pumShiftArrowActuated_())) ;

      % Timeline-statistic threshold row (enabled only for the
      % NEXTTIMELINETHRESH seek mode)
      obj.txTimelineProp_ = uicontrol(...
        'Parent', obj.hFig, ...
