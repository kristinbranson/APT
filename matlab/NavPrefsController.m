      if ~isempty(obj.parent_)
        mainFigurePosition = obj.parent_.mainFigurePixelPosition() ;
        centerOnOtherFigureGivenPositionBang(obj.hFig, mainFigurePosition) ;
      end
    end  % function

    function initControlsFromModel_(obj)
      % Populate the controls from the Labeler's current navigation
      % preferences (once, at open).
      labeler = obj.labeler_ ;

      obj.etFrameSkip_.String = num2str(labeler.movieFrameStepBig) ;
      obj.etPlaybackSpeed_.String = num2str(labeler.moviePlayFPS) ;
      obj.etPlaybackLoopDiameter_.String = num2str(labeler.moviePlaySegRadius) ;

      shiftArrowModes = enumeration('ShiftArrowMovieNavMode') ;
      obj.shiftArrowModes_ = shiftArrowModes ;
      pum = obj.pumShiftArrow_ ;
      pum.String = arrayfun(@(x)(x.prettyStr), shiftArrowModes, 'UniformOutput', false) ;
      pum.Value = find(labeler.movieShiftArrowNavMode == shiftArrowModes) ;

      obj.etShiftArrowTimelineThresh_.String = num2str(labeler.movieShiftArrowNavModeThresh) ;
      pum = obj.pumShiftArrowTimelineThreshCmp_ ;
      idx = find(strcmp(pum.String, labeler.movieShiftArrowNavModeThreshCmp)) ;
      assert(isscalar(idx)) ;
      pum.Value = idx ;

      infoTimelineModel = labeler.infoTimelineModel ;
      [~, timelineProp] = infoTimelineModel.getCurPropSmart() ;
      obj.txTimelineProp_.String = timelineProp.name ;
    end  % function

    function updateTimelineStatComparisonEnable_(obj)
      % Enable the timeline-statistic threshold row iff the selected seek
      % mode is NEXTTIMELINETHRESH.
      seekMode = obj.selectedShiftArrowMode_() ;
      isTimelineThresh = (seekMode == ShiftArrowMovieNavMode.NEXTTIMELINETHRESH) ;
      onoff = onIff(isTimelineThresh) ;

      obj.txTimelineProp_.Enable = onoff ;
      obj.pumShiftArrowTimelineThreshCmp_.Enable = onoff ;
      obj.etShiftArrowTimelineThresh_.Enable = onoff ;
    end  % function

    function seekMode = selectedShiftArrowMode_(obj)
      % The ShiftArrowMovieNavMode currently selected in pumShiftArrow_.
      seekMode = obj.shiftArrowModes_(obj.pumShiftArrow_.Value) ;
    end  % function

    %%%%%%%%%%%%%%%%%%%%%%%%%%
    % EDIT-FIELD VALIDATION  %
    %%%%%%%%%%%%%%%%%%%%%%%%%%

    function etFrameSkipActuated_(obj)
      % Revert to the model value if the entry is not a number.
      val = str2double(obj.etFrameSkip_.String) ;
      if isnan(val)
        obj.etFrameSkip_.String = num2str(obj.labeler_.movieFrameStepBig) ;
      end
    end  % function

    function etPlaybackSpeedActuated_(obj)
      % Revert to the model value if the entry is not a positive number.
      val = str2double(obj.etPlaybackSpeed_.String) ;
      if isnan(val) || val <= 0
        obj.etPlaybackSpeed_.String = num2str(obj.labeler_.moviePlayFPS) ;
      end
    end  % function

    function etPlaybackLoopDiameterActuated_(obj)
      % Revert to the model value if the entry is not a positive number.
      val = str2double(obj.etPlaybackLoopDiameter_.String) ;
      if isnan(val) || val <= 0
        obj.etPlaybackLoopDiameter_.String = num2str(obj.labeler_.moviePlaySegRadius) ;
      end
    end  % function

    function etShiftArrowTimelineThreshActuated_(obj)
      % Revert to the model value if the entry is not a number.
      val = str2double(obj.etShiftArrowTimelineThresh_.String) ;
      if isnan(val)
        obj.etShiftArrowTimelineThresh_.String = num2str(obj.labeler_.movieShiftArrowNavModeThresh) ;
      end
    end  % function

    function pumShiftArrowActuated_(obj)
      % The seek mode changed; the threshold row applies only to one mode.
      obj.updateTimelineStatComparisonEnable_() ;
    end  % function

    %%%%%%%%%%%%%%%%%%%%
    % APPLY/CANCEL/ETC %
    %%%%%%%%%%%%%%%%%%%%

    function applyActuated_(obj)
      % Write the edited preferences to the Labeler, then close the dialog.
      obj.writePreferencesToModel_() ;
      obj.closeRequested_() ;
    end  % function

    function writePreferencesToModel_(obj)
      % Write the edited preferences to the Labeler.
      obj.labeler_.movieFrameStepBig = str2double(obj.etFrameSkip_.String) ;
      obj.labeler_.moviePlayFPS = str2double(obj.etPlaybackSpeed_.String) ;
      obj.labeler_.moviePlaySegRadius = str2double(obj.etPlaybackLoopDiameter_.String) ;
      seekMode = obj.selectedShiftArrowMode_() ;
      obj.labeler_.movieShiftArrowNavMode = seekMode ;

      if seekMode == ShiftArrowMovieNavMode.NEXTTIMELINETHRESH
        pum = obj.pumShiftArrowTimelineThreshCmp_ ;
        cmp = pum.String{pum.Value} ;
        thresh = str2double(obj.etShiftArrowTimelineThresh_.String) ;
        obj.labeler_.setMovieShiftArrowNavModeThresh(thresh) ;
        obj.labeler_.movieShiftArrowNavModeThreshCmp = cmp ;
      end
    end  % function

    function cancelActuated_(obj)
      % Discard the edits and close the dialog.
      obj.closeRequested_() ;
    end  % function

    function closeRequested_(obj)
      % Close the dialog (non-blocking; nothing is applied on close).
      delete(obj) ;
    end  % function

  end  % methods
end  % classdef
