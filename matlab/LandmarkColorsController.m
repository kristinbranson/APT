    function saveState_(obj)
      % Compute the set of changed specs, storing it in obj.saved_.
      tfApplyAll = obj.cbApplyAll_.Value ;
      iCS = obj.pumShowing_.Value ;
      if tfApplyAll
        colorSpecs = obj.colorSpecs_ ;
        for i = 1:numel(colorSpecs)
          if i == iCS
            continue ;
          end
          colorSpecs(i).copyColorState(colorSpecs(iCS)) ;
        end
        colorSpecs0 = obj.colorSpecs0_ ;
      else
        colorSpecs = obj.colorSpecs_(iCS) ;
        colorSpecs0 = obj.colorSpecs0_(iCS) ;
      end
      colorSpecs.setManualColorsToColormapIfNec() ;
      sPropsMrkr = obj.markerControlsGet_() ;
      sPropsSkel = obj.skelControlsGet_() ;

      tfclrchanged = ~arrayfun(@isequal, colorSpecs, colorSpecs0) ;
      % handles.sPropsMrkr0 might have properties that are not visible/editable
      % in the UI, hence the structoverlay comparison.
      tfmkrchanged = ~arrayfun(@(x,y)isequaln(x,structoverlay(x,y)), ...
        obj.sPropsMrkr0_, sPropsMrkr) ;
      tfskelchanged = ~arrayfun(@(x,y)isequaln(x,structoverlay(x,y)), ...
        obj.sPropsSkel0_, sPropsSkel) ;

      obj.saved_ = struct(...
        'colorSpecs', colorSpecs(tfclrchanged), ...
        'markerSpecs', sPropsMrkr(tfmkrchanged), ...
        'skeletonSpecs', sPropsSkel(tfskelchanged) ...
        ) ;
      % Note any field of obj.saved_ could be empty.
    end  % function

    function applyActuated_(obj)
      obj.saveState_() ;
      saved = obj.saved_ ;
      obj.applyCbkFcn_(saved.colorSpecs, saved.markerSpecs, saved.skeletonSpecs) ;
    end  % function

    function doneActuated_(obj)
      % Apply happens live on every edit, so Done simply closes the dialog.
      obj.closeRequested_() ;
    end  % function

    function tblCellEditActuated_(obj)
      obj.applyActuated_() ;
    end  % function

    function sldSkeletonLineWidthActuated_(obj)
      obj.applyActuated_() ;
    end  % function

    function pbSkeletonColorActuated_(obj)
      c0 = obj.pbSkeletonColor_.BackgroundColor ;
      clr = uisetcolor(c0) ;
      % uisetcolor returns the empty array if the user cancels the dialog; in
      % that case leave the skeleton color unchanged and do not re-apply.
      if isempty(clr)
        return ;
      end
      obj.pbSkeletonColor_.BackgroundColor = clr ;
      obj.applyActuated_() ;
    end  % function

    function closeRequested_(obj)
      % Close the dialog (non-blocking; live-applied changes remain in effect).
      delete(obj) ;
    end  % function

  end  % methods
end  % classdef
