classdef LandmarkColorsController < handle
  % Controller for the "Landmark Cosmetics" dialog (keypoint appearance:
  % per-landmark colors, marker/label properties, and skeleton cosmetics).
  %
  % This replaces the legacy GUIDE app LandmarkColors.m / LandmarkColors.fig.
  % The figure is built programmatically in createGui_() (layout lifted from
  % GUIDE's export), the widget handles live as instance properties (no more
  % guidata reach-throughs), and the dialog is modal but non-blocking (no
  % uiwait): edits are applied to the model live via the apply callback, so the
  % constructor returns immediately.

  properties (Transient)
    hFig  % the dialog figure
    parent_  % a LabelerController
    labeler_  % a Labeler
    applyCbkFcn_  % cbk(colorSpecs, markerSpecs, skeletonSpecs)

    % State (formerly stored in guidata)
    nlandmarks_
    colorSpecs_  % array of LandmarkColorSpec; live color state, edited in place
    colorSpecs0_  % copy of colorSpecs_ at open, for change detection
    sPropsMrkr0_  % marker/label state at open, for change detection
    sPropsSkel0_  % skeleton state at open, for change detection
    colormapim_  % image handle in the colormap-preview axes
    hbuttons_  % [1 x nlandmarks] per-landmark manual-color pushbuttons
    hSldListener_  % listener on the skeleton-line-width slider's ContinuousValueChange
    saved_  % struct of changed specs, set by saveState_()

    % Widget handles, formerly reached via guidata(obj.hFig).
    pbDone_
    pnlTab_
    uibuttongroup1_  % the "Colors" button group (colormap vs. manual)
    radiobutton_colormap_
    radiobutton_manual_
    uipanel_manual_
    uipanel_colormap_
    axes_colormap_
    popupmenu_colormap_
    slider_brightness_
    edit_brightness_
    pumShowing_
    cbApplyAll_
    pnlMarkersLabels_
    tblProps_
    uipanel6_  % the "Skeleton" panel
    sldSkeletonLineWidth_
    pbSkeletonColor_
  end  % properties

  methods
    function obj = LandmarkColorsController(parent, labeler, applyCbkFcn)
      % Build the dialog and initialize its state from the Labeler.
      % applyCbkFcn signature: cbk(colorSpecs, markerSpecs, skeletonSpecs).
      obj.parent_ = parent ;
      obj.labeler_ = labeler ;
      obj.applyCbkFcn_ = applyCbkFcn ;
      obj.nlandmarks_ = labeler.nPhysPoints ;

      obj.createGui_() ;

      % Marker state -- lives only in the table; get/set via markerControls*_.
      lsetTypesCell = num2cell(enumeration('LandmarkSetType')) ;
      ppiAll = {labeler.labelPointsPlotInfo ; labeler.predPointsPlotInfo} ;
      FLDS = {'MarkerProps' 'TextProps' 'TextOffset'} ;
      sPropsMrkr = cellfun(@(x)structrestrictflds(x,FLDS), ppiAll) ;
      [sPropsMrkr.landmarkSetType] = deal(lsetTypesCell{:}) ;
      % Color state -- maintained in obj.colorSpecs_; the Colors pane shows the
      % spec selected by pumShowing_.
      lsetTypesCellCount = numel(lsetTypesCell) ;
      obj.colorSpecs_ = ...
        cellfun(@(x1,x2,x3)LandmarkColorSpec(x1,x2,x3), ...
                lsetTypesCell, ...
                repmat({labeler.nPhysPoints}, lsetTypesCellCount, 1), ...
                ppiAll) ;
      % Skeleton state
      FLDS = {'SkeletonProps'} ;
      sPropsSkel = cellfun(@(x)structrestrictflds(x,FLDS), ppiAll) ;
      [sPropsSkel.landmarkSetType] = deal(lsetTypesCell{:}) ;

      obj.sPropsMrkr0_ = sPropsMrkr ;
      obj.colorSpecs0_ = obj.colorSpecs_.copy() ;
      obj.sPropsSkel0_ = sPropsSkel ;

      obj.initColorsPane_() ;
      obj.updateColorsPane_() ;

      MARKERS = num2cell('o+*.xsd^v><ph') ;
      tbl = obj.tblProps_ ;
      tbl.ColumnFormat{1} = MARKERS ;
      tbl.ColumnFormat{6} = {'normal' 'italic'} ;
      ncol = numel(tbl.ColumnFormat) ;
      set(tbl, 'Data', cell(3,ncol), 'RowName', {'Label' 'Prediction'}) ;

      obj.markerControlsSet_(sPropsMrkr) ;

      obj.sldSkeletonLineWidth_.Min = -1 ;  % log scale
      obj.sldSkeletonLineWidth_.Max = 5 ;
      obj.hSldListener_ = ...
        addlistener(obj.sldSkeletonLineWidth_, 'ContinuousValueChange', ...
                    @(s,e)(obj.sldSkeletonLineWidthActuated_())) ;
      obj.skelControlsSet_(sPropsSkel) ;

      obj.saved_ = [] ;
      obj.tblProps_.CellEditCallback = @(s,e)(obj.tblCellEditActuated_()) ;
    end  % function

    function delete(obj)
      % Tear down the listener and figure.
      if ~isempty(obj.hSldListener_) && isvalid(obj.hSldListener_)
        delete(obj.hSldListener_) ;
      end
      deleteValidGraphicsHandles(obj.hFig) ;
      obj.hFig = [] ;
    end  % function

