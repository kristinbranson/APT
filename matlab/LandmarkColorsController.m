    function initColorsPane_(obj)
      % Populate the static parts of the Colors pane (once, at open).
      pum = obj.pumShowing_ ;
      pum.String = {'Labels' ; 'Predictions'} ;
      pum.Value = 1 ;

      % Colormap pulldown options
      pum = obj.popupmenu_colormap_ ;
      cmapnames = LandmarkColorSpec.CMAPNAMES ;
      ncmapnames = numel(cmapnames) ;
      cmapname2idx = cell2struct(num2cell(1:ncmapnames), cmapnames, 2) ;
      set(pum, 'String', LandmarkColorSpec.CMAPNAMES, 'Value', 1, 'UserData', cmapname2idx) ;

      obj.colormapim_ = imagesc(1:obj.nlandmarks_, 'Parent', obj.axes_colormap_) ;
      axis(obj.axes_colormap_, 'off') ;

      % create per-landmark manual-color buttons
      w = 1/obj.nlandmarks_ ;
      borderfrac = .05 ;
      for i = 1:obj.nlandmarks_
        obj.hbuttons_(i) = uicontrol(...
          'style', 'pushbutton', ...
          'ForegroundColor', 'k', ...
          'BackgroundColor', [0.5 0.5 0.5], ...
          'Units', 'normalized', ...
          'Position', [w*borderfrac+w*(i-1), borderfrac, w*(1-2*borderfrac), 1-2*borderfrac], ...
          'Parent', obj.uipanel_manual_, ...
          'Callback', @(s,e)(obj.pushbuttonManualActuated_(i)), ...
          'Tag', sprintf('pushbutton_manual_%d', i), ...
          'String', num2str(i)) ;
      end
    end  % function

    function updateColorsPane_(obj)
      % Sync the Colors pane uicontrols to the currently-shown colorSpec.
      cs = obj.colorSpecs_(obj.pumShowing_.Value) ;

      % mode
      btnGrp = obj.radiobutton_manual_.Parent ;
      if cs.tfmanual
        btnGrp.SelectedObject = obj.radiobutton_manual_ ;
      else
        btnGrp.SelectedObject = obj.radiobutton_colormap_ ;
      end

      obj.updateColorMode_() ;

      if cs.tfmanual
        % manual button colors
        for i = 1:obj.nlandmarks_
          set(obj.hbuttons_(i), 'BackgroundColor', cs.colors(i,:)) ;
        end
      else
        % colormapname
        cmapname = cs.colormapname ;
        pumcmap = obj.popupmenu_colormap_ ;
        cmapidx = pumcmap.UserData.(cmapname) ;
        pumcmap.Value = cmapidx ;

        % colormap
        colormap(obj.axes_colormap_, cs.colormap) ;

        % brightness
        set(obj.edit_brightness_, 'String', num2str(cs.brightness)) ;
        set(obj.slider_brightness_, 'Value', cs.brightness) ;
      end
    end  % function

    function updateColorMode_(obj)
      % Enable/disable colormap vs. manual panes based on the mode radiobutton.
      v = get(obj.radiobutton_manual_, 'Value') ;
      hcm = findobj(obj.uipanel_colormap_, '-property', 'Enable') ;
      hm = findobj(obj.uipanel_manual_, '-property', 'Enable') ;
      if v == 1
        set(hcm, 'Enable', 'off') ;
        set(hm, 'Enable', 'on') ;
      else
        set(hcm, 'Enable', 'on') ;
        set(hm, 'Enable', 'off') ;
      end
    end  % function

    function pumShowingActuated_(obj)
      obj.updateColorsPane_() ;
    end  % function

    function popupmenuColormapActuated_(obj)
      contents = cellstr(get(obj.popupmenu_colormap_, 'String')) ;
      cmapname = contents{get(obj.popupmenu_colormap_, 'Value')} ;
      cs = obj.colorSpecs_(obj.pumShowing_.Value) ;
      cs.setColormapName(cmapname) ;
      obj.updateColorsPane_() ;
      obj.applyActuated_() ;
    end  % function

    function sliderBrightnessActuated_(obj)
      v = get(obj.slider_brightness_, 'Value') ;
      cs = obj.colorSpecs_(obj.pumShowing_.Value) ;
      cs.setBrightness(v) ;
      obj.updateColorsPane_() ;
      obj.applyActuated_() ;
    end  % function

    function editBrightnessActuated_(obj)
      v = str2double(get(obj.edit_brightness_, 'String')) ;
      cs = obj.colorSpecs_(obj.pumShowing_.Value) ;
      if isnan(v) || v < 0 || v > 1
        warndlg('Brightness must be a number between 0 and 1', 'Error setting brightness', 'modal') ;
        set(obj.edit_brightness_, 'String', num2str(cs.brightness)) ;
      else
        cs.setBrightness(v) ;
        obj.updateColorsPane_() ;
        obj.applyActuated_() ;
      end
    end  % function

    function radiobuttonColormapActuated_(obj)
      cs = obj.colorSpecs_(obj.pumShowing_.Value) ;
      cs.setTFManual(false) ;
      obj.updateColorsPane_() ;
    end  % function

    function radiobuttonManualActuated_(obj)
      cs = obj.colorSpecs_(obj.pumShowing_.Value) ;
      cs.setManualColorsToColormap() ;
      cs.setTFManual(true) ;
      obj.updateColorsPane_() ;
    end  % function

    function pushbuttonManualActuated_(obj, landmarki)
      cs = obj.colorSpecs_(obj.pumShowing_.Value) ;
      clr = uisetcolor(cs.colors(landmarki,:), sprintf('Landmark %d color', landmarki)) ;
      % uisetcolor returns the empty array if the user cancels the dialog; in
      % that case leave the landmark color unchanged and do not re-apply.
      if isempty(clr)
        return ;
      end
      cs.setColorManual(landmarki, clr) ;
      obj.updateColorsPane_() ;
      obj.applyActuated_() ;
    end  % function

